_DAYS = {
    "en": ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"],
    "hinglish": ["Somvaar", "Mangalvaar", "Budhvaar", "Guruvaar", "Shukravaar", "Shanivaar", "Ravivaar"],
    "hi": ["सोमवार", "मंगलवार", "बुधवार", "गुरुवार", "शुक्रवार", "शनिवार", "रविवार"],
}
_MONTHS_EN = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def say(lang: str, key: str, **kw: object) -> str:
    return T[key].get(lang, T[key]["en"]).format(**kw)


def fmt_day(d: datetime, lang: str) -> str:
    return f"{_DAYS.get(lang, _DAYS['en'])[d.weekday()]} {d.day} {_MONTHS_EN[d.month - 1]}"


def fmt_time(d: datetime, lang: str) -> str:
    h12 = d.hour % 12 or 12
    if lang == "en":
        return f"{h12}:{d.minute:02d} {'AM' if d.hour < 12 else 'PM'}"
    part = "subah" if d.hour < 12 else "dopahar" if d.hour < 17 else "shaam"
    if lang == "hi":
        part = {"subah": "सुबह", "dopahar": "दोपहर", "shaam": "शाम"}[part]
    return f"{part} {h12}:{d.minute:02d}"


def fmt_when(d: datetime, lang: str) -> str:
    return f"{fmt_day(d, lang)}, {fmt_time(d, lang)}"


def fmt_options(slots: list[datetime], lang: str) -> str:
    return ", ".join(f"{i + 1}) {fmt_time(s, lang)}" for i, s in enumerate(slots))
